/**
 * What live Desmos returned for each edge case, in radian and degree mode.
 *
 * Recorded 2026-10-03 from desmos.com/calculator through
 * `Calc.HelperExpression`, with sliders a_{third} = 1/3, a_{half} = 1/2,
 * a_{dec} = 0.3333333333333333 and a_{three} = 3 defined. A value is a number,
 * or "NaN", "Infinity" or "-Infinity" for what Desmos reports as undefined or
 * infinite; −0 is recorded as 0, since no comparison can tell them apart.
 *
 * `strictEvaluate.unit.test.ts` holds the CPU evaluator to these, and
 * `strictSemantics.int.test.ts` asks live Desmos again, so that a change on
 * Desmos's side fails a test rather than silently moving a wall.
 */

export type ProbeValue = number | "NaN" | "Infinity" | "-Infinity";

